import { el, pageHeader, alertBox, asyncButton, loadingCard } from "../ui.js";
import { icon } from "../icons.js";
import { api } from "../api.js";
import { imageResult } from "./shared.js";

const MAX = 5 * 1024 * 1024;

export async function imagePage() {
  let source = null; // {blob, url, sample}
  const result = el("div", { "aria-live": "polite" }), preview = el("div"), msg = el("div");
  const file = el("input", { type: "file", id: "imgfile", accept: "image/jpeg,image/png,.jpg,.jpeg,.png" });
  const drop = el("label", { class: "dropzone", for: "imgfile" }, icon("upload"), el("strong", {}, "Choose a JPG or PNG image or drop it here"), el("span", { class: "muted" }, "Up to 5 MB. Processed in memory and not stored."), file);
  const analyse = el("button", { class: "btn", type: "button", hidden: true }, "Start analysis");

  function setSource(s, caption) {
    if (source?.url) URL.revokeObjectURL(source.url);
    source = s; result.replaceChildren(); msg.replaceChildren();
    preview.replaceChildren(el("div", { class: "preview" }, el("img", { src: s.url, alt: "Preview of the selected image" })), el("p", { class: "muted" }, caption));
    analyse.hidden = false;
  }
  function pick(f) {
    msg.replaceChildren();
    if (!f) return;
    if (!["image/jpeg", "image/png"].includes(f.type)) return msg.append(alertBox("bad", "Only JPG, JPEG or PNG images are accepted."));
    if (f.size > MAX) return msg.append(alertBox("bad", "That file is larger than 5 MB. Choose a smaller image."));
    setSource({ blob: f, url: URL.createObjectURL(f) }, `${f.name.replace(/[<>]/g, "")} - selected on your device. It is analysed in memory and never stored.`);
  }
  file.addEventListener("change", () => pick(file.files[0]));
  ["dragenter", "dragover"].forEach((t) => drop.addEventListener(t, (e) => { e.preventDefault(); drop.classList.add("drag"); }));
  ["dragleave", "drop"].forEach((t) => drop.addEventListener(t, (e) => { e.preventDefault(); drop.classList.remove("drag"); }));
  drop.addEventListener("drop", (e) => pick(e.dataTransfer.files[0]));

  const sampleBtn = asyncButton("Use synthetic sample image (demonstration data)", async () => {
    try {
      const res = await fetch("/api/image/sample"); const blob = await res.blob();
      setSource({ blob, url: URL.createObjectURL(blob), sample: true }, "Synthetic sample generated by the server. Not a photo of a real person. Demonstration data.");
    } catch { msg.replaceChildren(alertBox("bad", "Could not load the sample image.")); }
  }, "btn ghost small");

  analyse.addEventListener("click", async () => {
    if (!source) return;
    analyse.disabled = true; result.replaceChildren(loadingCard("Running metadata, Error Level Analysis and face-region checks\u2026"));
    try {
      const r = source.sample ? await api.post("/api/image/analyse-sample") : await api.image(source.blob);
      result.replaceChildren(imageResult(r, source.url)); result.firstChild.scrollIntoView({ behavior: "smooth", block: "start" });
    } catch (e) { result.replaceChildren(alertBox("bad", e.message)); }
    finally { analyse.disabled = false; }
  });
  return [...pageHeader(["working"], "Deepfake and image analysis", "Upload an image to run real file-level checks: metadata, edit traces (Error Level Analysis) and face-region detection."),
    alertBox("warn", el("strong", {}, "This is not a deepfake detector. "), "No trained AI model is installed. It cannot tell whether a face is swapped or AI-generated, and it never gives a \"percent fake\" score. ", el("strong", {}, "Image analysis cannot establish whether an image is genuine or manipulated with complete certainty.")),
    el("div", { class: "card" }, drop, msg, el("p", {}, el("strong", {}, "No image handy? "), sampleBtn), preview, el("div", { class: "actions" }, analyse)), result];
}
